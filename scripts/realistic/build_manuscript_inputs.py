def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    parser.add_argument("--paper", type=Path, default=DEFAULT_PAPER)
    args = parser.parse_args()
    processed = args.root / "processed"
    tables, figures = args.paper / "tables", args.paper / "figures"
    tables.mkdir(parents=True, exist_ok=True)
    figures.mkdir(parents=True, exist_ok=True)

    macros = Macros()
    for build in BUILDERS:
        build(macros, processed)
    macros.write(tables / "result_macros.tex")
    print(f"wrote {len(macros.rows)} macros to {tables / 'result_macros.tex'}")

    for name, build_table in (("generated_planner_decision_quality.tex", planner_table),
                              ("generated_planner_decision_quality_compact.tex", planner_table_compact)):
        table = build_table(processed)
        if table is not None:
            (tables / name).write_text(table, encoding="utf-8")
            print(f"wrote {name}")
    example = intent_example(args.root)
    if example is not None:
        (tables / "generated_intent_example.tex").write_text(example, encoding="utf-8")
        print("wrote generated_intent_example.tex")

    copied = 0
    for figure in sorted((args.root / "figures").glob("*.pdf")):
        shutil.copy2(figure, figures / figure.name)
        copied += 1
    print(f"copied {copied} figure(s) to {figures}")


if __name__ == "__main__":
    main()
