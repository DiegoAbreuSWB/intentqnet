def physics_macros(m: Macros, processed: Path) -> None:
    """Closed-form reference points of the two hardware conditions, computed
    by the same code the planners use (`ibqn.physics`,
    `planning.planners.generation_models`) - not read from a results file."""
    import sys

    sys.path.insert(0, str(PROJECT_ROOT / "src"))
    from ibqn.experiments.realistic_suite import HARDWARE as PROFILES
    from ibqn.experiments.realistic_topologies import DEFAULT_LINK_M, realistic_chain
    from ibqn.network.capabilities import NetworkCapabilities
    from ibqn.network.platforms import resolve_platform
    from ibqn.planning.feasibility import estimate_swap_only_fidelity
    from ibqn.planning.planners.generation_models import attempt_cycle_s, estimate_generation, hop_success_probability

    for hardware, profile_name in PROFILES.items():
        profile = resolve_platform(profile_name)
        src = f"ibqn.physics on platform {profile_name}"
        for swaps in (1, 2, 3):
            spec = realistic_chain(swaps, platform=profile)
            capabilities = NetworkCapabilities(spec)
            route = [node.id for node in spec.nodes]
            fidelity, _ = estimate_swap_only_fidelity(capabilities, route)
            prefix = macro_name("Phys", hardware, f"Swaps{swaps}")
            m.number(prefix + "Fidelity", fidelity, src, 3)
            one_round = capabilities.physics.purification_between(route[0], route[-1])
            for rounds in (1, 2, 3):
                success, fidelity = one_round.improve(fidelity)
                m.number(prefix + macro_name(f"Rounds{rounds}") + "Fidelity", fidelity, src, 3)
                if rounds == 1:
                    m.percent(prefix + "RoundOneSuccess", success, src, 0)
            if hardware == "literature":
                slots = spec.nodes[0].memories
                m.number(macro_name("Phys", f"Swaps{swaps}", "BufferedRate"),
                         estimate_generation(capabilities, route, slots, model="buffered").raw_end_to_end_pair_rate, src, 0)
                m.number(macro_name("Phys", f"Swaps{swaps}", "SameCycleRate"),
                         estimate_generation(capabilities, route, slots, model="same_cycle").raw_end_to_end_pair_rate, src, 2)
    profile = resolve_platform(PROFILES["literature"])
    capabilities = NetworkCapabilities(realistic_chain(1, platform=profile))
    src = "generation_models on platform siv_2024, 5 km link"
    p = hop_success_probability(capabilities, "a", "r1")
    cycle = attempt_cycle_s(capabilities, "a", "r1")
    m.number("PhysAttemptSuccessPerMille", 1000 * p, src, 1)
    m.number("PhysAttemptCycleMicroseconds", 1e6 * cycle, src, 0)
    m.number("PhysPairsPerMemorySecond", p / cycle, src, 0)
    m.number("PhysLinkKilometres", DEFAULT_LINK_M / 1000, src, 0)
    for name, value, digits in (("RawFidelity", profile.raw_fidelity, 2), ("GateFidelity", profile.gate_fidelity, 3),
                                ("MeasurementFidelity", profile.measurement_fidelity, 3),
                                ("CoherenceSeconds", profile.coherence_time_s, 0), ("MemoryEfficiency", profile.memory_efficiency, 2),
                                ("DetectorEfficiency", profile.detector_efficiency, 1),
                                ("AttenuationDbPerKm", 1000 * profile.attenuation_db_per_m, 1),
                                ("CutoffSeconds", profile.cutoff_ratio * profile.coherence_time_s, 0)):
        m.number("Hw" + name, value, "network.platforms.SIV_2024", digits)


def audit_macros(m: Macros, processed: Path) -> None:
    integrity = read(processed, "r00_state_integrity_audit")
    if integrity is not None:
        row, src = integrity.iloc[0], "r00_state_integrity_audit.csv"
        m.count("AuditIntegrityRuns", row["runs"], src)
        m.count("AuditIntegrityAborted", row["aborted"], src)
        m.count("AuditIntegrityDangling", row["dangling_states_at_end"], src)
        m.count("AuditSwapInputs", sum(row[c] for c in integrity.columns if c.startswith("swap_input_")), src)
        m.count("AuditSwapInputsIntact", row["swap_input_ok"], src)
        m.count("AuditPurificationInputs", sum(row[c] for c in integrity.columns if c.startswith("purification_input_")), src)
        m.count("AuditPurificationInputsIntact", row["purification_input_ok"], src)
        m.count("AuditDecoherenceCalls", sum(row[c] for c in integrity.columns if c.startswith("decohere_")), src)
        m.count("AuditDecoherenceNoState", row["decohere_no_state"], src)
        m.count("AuditDecoherenceStale", row["decohere_stale_recreate"] + row["decohere_stale_overwrite"], src)
        m.count("AuditDecoherenceOverwrite", row["decohere_stale_overwrite"], src)
        m.count("AuditDecoherenceRaces",
                row["decohere_no_state"] + row["decohere_stale_recreate"] + row["decohere_stale_overwrite"], src)
    generation = read(processed, "r00_generation_model_audit")
    if generation is not None:
        src = "r00_generation_model_audit.csv"
        forward = generation[~generation["reverse"].astype(bool)]
        multi = forward[forward["n_repeaters"] > 0]
        direct = forward[forward["n_repeaters"] == 0]
        m.count("AuditGenerationRuns", generation["runs"].sum(), src)
        m.count("AuditGenerationCells", len(multi), src)
        m.number("AuditBufferedPooledRatio", multi["delivered"].sum() / (multi["rate_model"] * multi["window"]).sum(), src, 3)
        m.number("AuditBufferedSecondHalfRatio",
                 multi["second_half"].sum() / (multi["rate_model"] * multi["window"] / 2).sum(), src, 3)
        m.percent("AuditBufferedMeanAbsError", (multi["measured/model"] - 1).abs().mean(), src)
        m.number("AuditBufferedMinRatio", multi["measured/model"].min(), src, 2)
        m.number("AuditBufferedMaxRatio", multi["measured/model"].max(), src, 2)
        m.number("AuditDirectPooledRatio", direct["delivered"].sum() / (direct["rate_model"] * direct["window"]).sum(), src, 3)
        m.number("AuditSameCycleMinFactor", multi["measured/same_cycle"].min(), src, 0)
        one_repeater = multi[multi["n_repeaters"] == 1]
        m.number("AuditSameCycleOneRepeaterFactor",
                 one_repeater["delivered"].sum() / (one_repeater["rate_same_cycle"] * one_repeater["window"]).sum(), src, 0)


